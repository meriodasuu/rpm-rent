const isPublishableCopy = (value: string | null | undefined) => {
  const copy = value?.trim();
  return Boolean(copy && !/(dev[- ]?верси|демонстрацион|перед публикаци|фотокаталог|требуется от владельца)/i.test(copy));
};

export const getCarEditorial = (car: Car) => {
  const editorial = carEditorial[car.slug] ?? fallbackEditorial(car);
  return {
    ...editorial,
    // The primary lead remains editable through the existing car admin form.
    // Draft/dev copy is never exposed and falls back to the verified editorial preset.
    intro: isPublishableCopy(car.shortDescription) ? car.shortDescription.trim() : editorial.intro
  };
};

